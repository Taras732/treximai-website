export function getRelated(article: Article, count = 3): Article[] {
  const others = articles.filter((a) => a.slug !== article.slug);
  // Score by tag overlap
  const scored = others.map((a) => ({
    article: a,
    overlap: a.tags.filter((t) => article.tags.includes(t)).length,
  }));
  scored.sort((a, b) => b.overlap - a.overlap || +new Date(b.article.date) - +new Date(a.article.date));
  return scored.slice(0, count).map((s) => s.article);
}
